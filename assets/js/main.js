function renderDetailPage() {
  const pageType = location.pathname.includes('project-detail') ? 'project' : 'activity';
  const queryId = new URLSearchParams(location.search).get('id');
  const dataSet = pageType === 'project' ? projectData : activityData;
  const item = dataSet.find((entry) => entry.id === queryId) || dataSet[0];

  const titleEl = document.querySelector('[data-detail-title]');
  const summaryEl = document.querySelector('[data-detail-summary]');
  const listEl = document.querySelector('[data-detail-list]');
  const categoryKoEl = document.querySelector('[data-detail-category-ko]');
  const categoryEnEl = document.querySelector('[data-detail-category-en]');
  const sourcesEl = document.querySelector('[data-detail-sources]');

  if (!titleEl || !summaryEl || !listEl) return;

  titleEl.innerHTML = `
    <span class="lang-ko">${item.titleKo}</span>
    <span class="lang-en">${item.titleEn}</span>
  `;

  summaryEl.innerHTML = `
    <span class="lang-ko">${item.summaryKo}</span>
    <span class="lang-en">${item.summaryEn}</span>
  `;

  if (categoryKoEl) categoryKoEl.textContent = item.categoryKo;
  if (categoryEnEl) categoryEnEl.textContent = item.categoryEn;

  listEl.innerHTML = (item.detailsKo || item.detailsEn).map((detail, idx) => `
    <li>
      <span class="lang-ko">${item.detailsKo[idx]}</span>
      <span class="lang-en">${item.detailsEn[idx]}</span>
    </li>
  `).join('');

  if (sourcesEl) {
    sourcesEl.innerHTML = (item.sourceFiles || []).map((file) => `
      <li><a href="${encodeURI(file)}" target="_blank" rel="noreferrer">${file}</a></li>
    `).join('');
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const preferredLang = localStorage.getItem('portfolio-lang') || 'ko';
  const preferredTheme = localStorage.getItem('portfolio-theme') || 'light';

  applyTheme(preferredTheme);
  applyLanguage(preferredLang);

  document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
    button.addEventListener('click', () => {
      const nextLang = button.dataset.langToggle;
      applyLanguage(nextLang);
    });
  });

  document.querySelector('[data-theme-toggle]')?.addEventListener('click', () => {
    const nextTheme = document.body.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    applyTheme(nextTheme);
  });

  renderProjects();
  renderActivities();
  renderDetailPage();

  const navLinks = document.querySelectorAll('.nav-links a');
  const pageName = location.pathname.split('/').pop() || 'index.html';
  navLinks.forEach((link) => {
    const href = link.getAttribute('href');
    if (href === pageName || (pageName === '' && href === 'index.html')) {
      link.classList.add('active');
    }
  });
});
