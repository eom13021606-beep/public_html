async function loadPortfolioData(category, lang) {
  const currentLang = lang || (window.PortfolioLang ? window.PortfolioLang.getLang() : 'ko');
  try {
    const res = await fetch('data/' + category + '.' + currentLang + '.json');
    if (res.ok) {
      const data = await res.json();
      window.PortfolioData[category][currentLang] = data;
      return data;
    }
  } catch (e) {
    // Local file:/// protocol fallback
  }
  return window.PortfolioData[category][currentLang];
}

